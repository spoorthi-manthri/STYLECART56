// Helper: get all products for a given garment category
export function getProductsByCategory(category: GarmentCategory): Product[] {
  return sampleProducts.filter((p) => p.category === category);
}

// Helper: get all products for a given fabric type
export function getProductsByFabric(fabric: FabricCategory): Product[] {
  return sampleProducts.filter((p) => p.fabric === fabric);
}

// Helper: get products matching both a garment category and a fabric
export function getProductsByCategoryAndFabric(
  category: GarmentCategory,
  fabric: FabricCategory
): Product[] {
  return sampleProducts.filter((p) => p.category === category && p.fabric === fabric);
}
